"""Tests for the S3 storage backend.

Requests are checked with botocore's Stubber, so nothing reaches the network.
Presigned URLs are generated by a real client with fake credentials, which is
also offline.
"""

import io
from unittest.mock import MagicMock
from urllib.parse import parse_qs, urlparse

import pytest

from feather.exceptions import StorageError

boto3 = pytest.importorskip("boto3")
from botocore.stub import Stubber  # noqa: E402

from feather.storage.s3 import MissingS3Dependency, S3Storage  # noqa: E402

pytestmark = pytest.mark.integration

ENDPOINT = "http://s3.test:3900"


def make_storage(**kwargs):
    options = dict(
        bucket_name="uploads",
        endpoint_url=ENDPOINT,
        region="garage",
        access_key_id="GKtest",
        secret_access_key="secret",
    )
    options.update(kwargs)
    return S3Storage(**options)


@pytest.fixture
def storage():
    return make_storage()


@pytest.fixture
def stub(storage):
    with Stubber(storage.client) as stubber:
        yield stubber
        stubber.assert_no_pending_responses()


def not_found(stubber, method="head_object"):
    stubber.add_client_error(method, service_error_code="404" if method == "head_object" else "NoSuchKey",
                             http_status_code=404)


