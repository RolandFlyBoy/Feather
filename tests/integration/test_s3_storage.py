class TestOperations:
    def test_upload_bytes_puts_the_object_and_returns_a_presigned_url(self, storage, stub):
        stub.add_response(
            "put_object",
            {},
            {"Bucket": "uploads", "Key": "avatars/42.png", "Body": b"png", "ContentType": "image/png"},
        )
        url = storage.upload(b"png", "avatars/42.png")

        parsed = urlparse(url)
        assert f"{parsed.scheme}://{parsed.netloc}" == ENDPOINT
        assert parsed.path == "/uploads/avatars/42.png"  # path style
        query = parse_qs(parsed.query)
        assert query["X-Amz-Expires"] == ["3600"]
        assert "X-Amz-Signature" in query

    def test_upload_file_object_and_path(self, storage, tmp_path):
        storage.client = MagicMock()
        storage.client.generate_presigned_url.return_value = "https://signed"

        buffer = io.BytesIO(b"data")
        assert storage.upload(buffer, "docs/a.pdf") == "https://signed"
        storage.client.upload_fileobj.assert_called_once_with(
            buffer, "uploads", "docs/a.pdf", ExtraArgs={"ContentType": "application/pdf"}
        )

        source = tmp_path / "b.txt"
        source.write_text("hi")
        storage.upload(source, "docs/b.txt", content_type="text/plain")
        storage.client.upload_file.assert_called_once_with(
            str(source), "uploads", "docs/b.txt", ExtraArgs={"ContentType": "text/plain"}
        )

        with pytest.raises(StorageError, match="Source file not found"):
            storage.upload(tmp_path / "missing.txt", "docs/c.txt")

    def test_upload_failure_is_a_storage_error(self, storage, stub):
        stub.add_client_error("put_object", service_error_code="AccessDenied", http_status_code=403)
        with pytest.raises(StorageError, match="Failed to upload to S3"):
            storage.upload(b"x", "a.txt")

    def test_download(self, storage, stub):
        from botocore.response import StreamingBody

        body = StreamingBody(io.BytesIO(b"contents"), len(b"contents"))
        stub.add_response("get_object", {"Body": body}, {"Bucket": "uploads", "Key": "a.txt"})
        assert storage.download("a.txt") == b"contents"

    def test_download_missing_file(self, storage, stub):
        not_found(stub, "get_object")
        with pytest.raises(StorageError, match="File not found in S3"):
            storage.download("missing.txt")

    def test_exists(self, storage, stub):
        stub.add_response("head_object", {}, {"Bucket": "uploads", "Key": "a.txt"})
        not_found(stub)
        assert storage.exists("a.txt") is True
        assert storage.exists("b.txt") is False

    def test_exists_does_not_hide_access_errors(self, storage, stub):
        stub.add_client_error("head_object", service_error_code="403", http_status_code=403)
        with pytest.raises(StorageError, match="Failed to check S3 object"):
            storage.exists("a.txt")

    def test_delete(self, storage, stub):
        stub.add_response("head_object", {}, {"Bucket": "uploads", "Key": "a.txt"})
        stub.add_response("delete_object", {}, {"Bucket": "uploads", "Key": "a.txt"})
        not_found(stub)
        assert storage.delete("a.txt") is True
        assert storage.delete("a.txt") is False

    def test_get_url_presigns_with_options(self, storage, stub):
        stub.add_response("head_object", {}, {"Bucket": "uploads", "Key": "r/report.pdf"})
        url = storage.get_url("r/report.pdf", expires_in=60, download_name='Q3 "final".pdf',
                              content_type="application/pdf")
        query = parse_qs(urlparse(url).query)
        assert query["X-Amz-Expires"] == ["60"]
        assert query["response-content-disposition"] == ['inline; filename="Q3 final.pdf"']
        assert query["response-content-type"] == ["application/pdf"]

    def test_get_url_default_expiry_from_setting(self):
        storage = make_storage(url_expires="120")
        with Stubber(storage.client) as stubber:
            stubber.add_response("head_object", {}, {"Bucket": "uploads", "Key": "a.txt"})
            url = storage.get_url("a.txt")
        assert parse_qs(urlparse(url).query)["X-Amz-Expires"] == ["120"]

    def test_get_url_missing_file(self, storage, stub):
        not_found(stub)
        with pytest.raises(StorageError, match="File not found in S3"):
            storage.get_url("missing.txt")

    def test_public_url_skips_signing(self):
        storage = make_storage(public_url="https://cdn.example.com/")
        with Stubber(storage.client) as stubber:
            stubber.add_response("put_object", {}, None)
            stubber.add_response("head_object", {}, None)
            assert storage.upload(b"x", "a b/c.png") == "https://cdn.example.com/a%20b/c.png"
            assert storage.get_url("a b/c.png") == "https://cdn.example.com/a%20b/c.png"


