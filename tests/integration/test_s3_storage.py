class TestKeySafety:
    @pytest.mark.parametrize(
        "key",
        ["", "   ", "/etc/passwd", "a/../b.txt", "../b.txt", "a/./b.txt", "a//b.txt",
         "dir/", "a\\b.txt", "C:/x.txt", "bad\nname.txt", "bad\x00.txt"],
    )
    def test_unsafe_keys_are_refused_before_any_request(self, storage, key):
        storage.client = MagicMock()
        with pytest.raises(StorageError, match="Invalid storage path"):
            storage.upload(b"x", key)
        with pytest.raises(StorageError, match="Invalid storage path"):
            storage.exists(key)
        storage.client.put_object.assert_not_called()
        storage.client.head_object.assert_not_called()

    def test_overlong_key_is_refused(self, storage):
        with pytest.raises(StorageError, match="1024"):
            storage.exists("a" * 1025)

    @pytest.mark.parametrize("name", ["page.html", "x.SVG", "app.js", "a.php"])
    def test_script_capable_extensions_are_blocked(self, storage, name):
        storage.client = MagicMock()
        with pytest.raises(StorageError, match="blocked"):
            storage.upload(b"x", f"uploads/{name}")
        storage.client.put_object.assert_not_called()

    def test_allow_list_wins(self):
        storage = make_storage(allowed_extensions="png, .svg")
        storage.client = MagicMock()
        storage.client.generate_presigned_url.return_value = "https://signed"
        storage.upload(b"<svg/>", "logo.svg")
        with pytest.raises(StorageError, match="not allowed"):
            storage.upload(b"x", "notes.txt")

    def test_block_list_can_be_replaced(self):
        storage = make_storage(blocked_extensions="exe")
        storage.client = MagicMock()
        storage.client.generate_presigned_url.return_value = "https://signed"
        storage.upload(b"<svg/>", "logo.svg")
        with pytest.raises(StorageError, match="blocked"):
            storage.upload(b"x", "setup.exe")


