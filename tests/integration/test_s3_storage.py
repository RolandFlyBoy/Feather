class TestGetStorage:
    S3_KEYS = ("STORAGE_BACKEND", "S3_BUCKET", "S3_ENDPOINT", "S3_REGION", "S3_ACCESS_KEY_ID",
               "S3_SECRET_ACCESS_KEY", "S3_ADDRESSING_STYLE", "S3_URL_EXPIRES", "S3_PUBLIC_URL")

    @pytest.fixture(autouse=True)
    def clean_env(self, monkeypatch):
        for key in self.S3_KEYS:
            monkeypatch.delenv(key, raising=False)

    def test_env_injected_s3_settings_build_an_s3_backend(self, monkeypatch):
        from tests.conftest import feather_app
        from feather.storage import get_storage

        monkeypatch.setenv("S3_BUCKET", "app-files")
        monkeypatch.setenv("S3_ENDPOINT", ENDPOINT)
        monkeypatch.setenv("S3_REGION", "garage")
        monkeypatch.setenv("S3_ACCESS_KEY_ID", "GKtest")
        monkeypatch.setenv("S3_SECRET_ACCESS_KEY", "secret")
        monkeypatch.setenv("S3_URL_EXPIRES", "900")

        with feather_app() as app, app.app_context():
            storage = get_storage()

        assert isinstance(storage, S3Storage)
        assert storage.bucket_name == "app-files"
        assert storage.addressing_style == "path"
        assert storage.url_expires == 900

    def test_app_config_wins_over_env(self, monkeypatch):
        from tests.conftest import feather_app
        from feather.storage import get_storage

        monkeypatch.setenv("S3_BUCKET", "from-env")
        with feather_app(S3_BUCKET="from-config", S3_ACCESS_KEY_ID="a",
                         S3_SECRET_ACCESS_KEY="b", S3_REGION="us-east-1") as app:
            storage = get_storage(app)
        assert storage.bucket_name == "from-config"

    def test_explicit_s3_without_bucket_is_an_error(self):
        from tests.conftest import feather_app
        from feather.storage import get_storage

        with feather_app(STORAGE_BACKEND="s3") as app:
            with pytest.raises(StorageError, match="S3_BUCKET is required"):
                get_storage(app)

    def test_explicit_local_wins_over_s3_bucket(self, monkeypatch):
        from tests.conftest import feather_app
        from feather.storage import get_storage
        from feather.storage.local import LocalStorage

        monkeypatch.setenv("S3_BUCKET", "app-files")
        with feather_app(STORAGE_BACKEND="local") as app:
            assert isinstance(get_storage(app), LocalStorage)
