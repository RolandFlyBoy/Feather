class TestClientConfiguration:
    def test_custom_endpoint_uses_path_style_and_relaxed_checksums(self, storage):
        config = storage.client.meta.config
        assert storage.addressing_style == "path"
        assert config.s3["addressing_style"] == "path"
        assert config.request_checksum_calculation == "when_required"
        assert config.response_checksum_validation == "when_required"
        assert storage.client.meta.endpoint_url == ENDPOINT
        assert storage.client.meta.region_name == "garage"

    def test_aws_defaults_to_auto_and_keeps_boto_checksum_defaults(self):
        storage = S3Storage("uploads", region="eu-central-1",
                            access_key_id="AK", secret_access_key="SK")
        config = storage.client.meta.config
        assert storage.addressing_style == "auto"
        assert config.request_checksum_calculation != "when_required"

    def test_explicit_addressing_style_wins(self):
        storage = make_storage(addressing_style="virtual")
        assert storage.client.meta.config.s3["addressing_style"] == "virtual"

    def test_invalid_addressing_style_is_refused(self):
        with pytest.raises(StorageError, match="S3_ADDRESSING_STYLE"):
            make_storage(addressing_style="sideways")

    def test_half_a_credential_pair_is_refused(self):
        with pytest.raises(StorageError, match="S3_SECRET_ACCESS_KEY"):
            make_storage(secret_access_key=None)

    def test_missing_credentials_fall_back_to_the_boto3_chain(self, monkeypatch):
        monkeypatch.setenv("AWS_ACCESS_KEY_ID", "from-env")
        monkeypatch.setenv("AWS_SECRET_ACCESS_KEY", "from-env-secret")
        storage = make_storage(access_key_id=None, secret_access_key=None)
        assert storage.client._request_signer._credentials.access_key == "from-env"

    def test_bucket_is_required(self):
        with pytest.raises(StorageError, match="S3_BUCKET"):
            S3Storage("")

    def test_bad_url_expires_is_refused(self):
        with pytest.raises(StorageError, match="S3_URL_EXPIRES"):
            make_storage(url_expires="soon")

    def test_missing_boto3_names_the_extra(self):
        from tests.unit.test_optional_deps import hide_module

        with hide_module("boto3"), pytest.raises(MissingS3Dependency) as exc:
            S3Storage("uploads")
        message = str(exc.value)
        assert "pip install 'feather-framework[s3]'" in message
        assert isinstance(exc.value, ImportError)
        assert isinstance(exc.value, StorageError)


